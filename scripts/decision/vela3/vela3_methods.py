    _SENT = None

    @staticmethod
    def _paras(text):
        import re
        out, pos = [], 0
        for blk in re.split(r"(\n\s*\n|\n)", text):
            if blk and not re.fullmatch(r"\s*", blk):
                out.append((pos, pos + len(blk)))
            pos += len(blk)
        return out

    def _para_spans(self, pk, wo, text, thr, name):
        """R5 evidence decodes: "para" keeps a paragraph when its mean word probability reaches thr; "sentfill" keeps sentences at thr and
        fills a paragraph when at least half of its sentences are kept (r5_eval.decode2)."""
        import re
        if Vela3MiniModel._SENT is None:
            Vela3MiniModel._SENT = re.compile(r"[^.!?\n]+(?:[.!?]+|\n|$)")
        spans = []
        if name == "para":
            for a, b in self._paras(text):
                k = (wo[:, 0] >= a) & (wo[:, 1] <= b)
                if k.any() and pk[k].mean() >= thr:
                    spans.append([a, b])
            return spans
        sent = [(m.start(), m.end()) for m in Vela3MiniModel._SENT.finditer(text)]
        keep = []
        for a, b in sent:
            k = (wo[:, 0] >= a) & (wo[:, 1] <= b)
            keep.append(bool(k.any() and pk[k].mean() >= thr))
        for a, b in self._paras(text):
            inside = [i for i, (x, y) in enumerate(sent) if x >= a and y <= b]
            if inside and sum(keep[i] for i in inside) * 2 >= len(inside):
                spans.append([a, b])
            else:
                spans += [list(sent[i]) for i in inside if keep[i]]
        return spans

    def _evidence_spans(self, p, wo, names, text, thr, dc):
        """Evidence decoding picked on dev (ACL silver validation + RAGBench verbatim dev): "sent" keeps a sentence when the mean
        word probability of its first label reaches the threshold; "plain" is the word decoder; then spans <= gap characters apart
        are merged and spans shorter than min_chars dropped. One label (the first) carries the evidence spans."""
