        pk = p[:, 0]
        if dc["name"] in ("para", "sentfill"):  # R5: paragraph-scale decodes (picked on the gold-like ACL dev)
            spans = self._para_spans(pk, wo, text, thr, dc["name"])
        elif dc["name"] == "sent":
            if Vela3MiniModel._SENT is None:
                Vela3MiniModel._SENT = re.compile(r"[^.!?\n]+(?:[.!?]+|\n|$)")
            spans = []
            for m in Vela3MiniModel._SENT.finditer(text):
                a, b = m.start(), m.end(); k = (wo[:, 0] >= a) & (wo[:, 1] <= b)
                if k.any() and pk[k].mean() >= thr:
                    spans.append([a, b])
        else:
            spans = [[s["start"], s["end"]] for s in self._decode.decode_v2(pk[:, None], wo, names[:1], text, thr, extend=False)] if pk.max() > thr else []
        spans.sort(); out = []
        for s in spans:
            if out and s[0] - out[-1][1] <= dc.get("gap", 0):
                out[-1][1] = max(out[-1][1], s[1])
            else:
                out.append(list(s))
        return [dict(start=a, end=b, label=names[0]) for a, b in out if b - a >= dc.get("min_chars", 0)]

